//! Generates the design tokens from `design/tokens.json` (the one place they are defined):
//! Rust constants for `ui::theme` and the CSS that web pages use (`design/tokens.css`, kept in step by a
//! test in `ui::theme`).

use std::fmt::Write as _;
use std::path::PathBuf;

use serde_json::Value;

/// Sizes that egui takes as integers; the rest are f32 points.
const U8_SIZES: [&str; 2] = ["radius", "panel_radius"];
const I8_SIZES: [&str; 1] = ["panel_pad"];

fn rgb(hex: &str) -> (u8, u8, u8) {
    let h = hex.trim_start_matches('#');
    let p = |i: usize| u8::from_str_radix(&h[i..i + 2], 16).expect("colour must be #RRGGBB");
    (p(0), p(2), p(4))
}

fn fields(obj: &Value) -> Vec<(&str, &Value)> {
    obj.as_object().expect("object").iter().filter(|(k, _)| !k.starts_with('$')).map(|(k, v)| (k.as_str(), v)).collect()
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let path = manifest.join("../../design/tokens.json");
    println!("cargo:rerun-if-changed={}", path.display());
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let t: Value = serde_json::from_str(&text).expect("design/tokens.json is not valid JSON");

    let mut rs = String::from("// Generated by build.rs from design/tokens.json. Edit that file, not this one.\n\n");
    // colour tokens
    let roles = &t["color"]["$roles"];
    rs += "/// Colour tokens (design/tokens.json `color`).\npub struct Tokens {\n";
    for (name, _) in fields(&t["color"]["dark"]) {
        if let Some(role) = roles[name].as_str() {
            writeln!(rs, "    /// {role}").unwrap();
        }
        writeln!(rs, "    pub {name}: Color32,").unwrap();
    }
    rs += "}\n\n";
    for scheme in ["dark", "light"] {
        writeln!(rs, "pub const {}: Tokens = Tokens {{", scheme.to_uppercase()).unwrap();
        for (name, v) in fields(&t["color"][scheme]) {
            let (r, g, b) = rgb(v.as_str().expect("colour"));
            writeln!(rs, "    {name}: Color32::from_rgb({r:#04X}, {g:#04X}, {b:#04X}),").unwrap();
        }
        rs += "};\n\n";
    }
    // every colour with its name, for the component gallery
    let names: Vec<&str> = fields(&t["color"]["dark"]).into_iter().map(|(n, _)| n).collect();
    writeln!(rs, "impl Tokens {{\n    /// Every colour token with its name, in tokens.json order.\n    pub fn named(&self) -> [(&'static str, Color32); {}] {{\n        [", names.len()).unwrap();
    for n in &names {
        writeln!(rs, "            ({n:?}, self.{n}),").unwrap();
    }
    rs += "        ]\n    }\n}\n\n";
    // sizes
    rs += "/// Sizes in points (design/tokens.json `size`).\npub mod size {\n";
    for (name, v) in fields(&t["size"]) {
        let n = v.as_f64().expect("size");
        let (ty, val) = if U8_SIZES.contains(&name) {
            ("u8", format!("{}", n as u8))
        } else if I8_SIZES.contains(&name) {
            ("i8", format!("{}", n as i8))
        } else {
            ("f32", format!("{n:.1}"))
        };
        writeln!(rs, "    pub const {}: {ty} = {val};", name.to_uppercase()).unwrap();
    }
    rs += "}\n\n";
    // icons
    rs += "/// Phosphor (regular) icon glyphs, from `assets/Phosphor.ttf` (design/tokens.json `icon`).\n\
           /// Icons are text, so they take the text colour.\npub mod icon {\n";
    for (name, v) in fields(&t["icon"]) {
        writeln!(rs, "    pub const {}: &str = \"\\u{{{}}}\";", name.to_uppercase(), v.as_str().unwrap()).unwrap();
    }
    rs += "}\n\n";

    // CSS for web pages: light on :root, dark for the system dark setting and for data-theme="dark"
    let mut css = String::from(
        "/* PsConnector design tokens for web pages. Generated from design/tokens.json; do not edit.\n   \
         Regenerate: UPDATE_DESIGN_TOKENS=1 cargo test -p psconnector-view tokens */\n",
    );
    let colours = |scheme: &str, indent: &str| -> String {
        let mut s = String::new();
        for (name, v) in fields(&t["color"][scheme]) {
            writeln!(s, "{indent}--ps-{}: {};", name.replace('_', "-"), v.as_str().unwrap().to_lowercase()).unwrap();
        }
        s
    };
    css += ":root {\n";
    css += &colours("light", "  ");
    for (name, v) in fields(&t["size"]) {
        writeln!(css, "  --ps-{}: {}px;", name.replace('_', "-"), v.as_f64().unwrap()).unwrap();
    }
    let stack: Vec<String> = t["font"]["text"]
        .as_array()
        .unwrap()
        .iter()
        .map(|f| {
            let f = f.as_str().unwrap();
            if f.contains(' ') { format!("\"{f}\"") } else { f.to_string() }
        })
        .collect();
    writeln!(css, "  --ps-font-text: {};", stack.join(", ")).unwrap();
    css += "}\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n";
    css += &colours("dark", "    ");
    css += "    color-scheme: dark;\n  }\n}\n:root[data-theme=\"dark\"] {\n";
    css += &colours("dark", "  ");
    css += "  color-scheme: dark;\n}\n";
    writeln!(rs, "/// The web version of the tokens; `design/tokens.css` must match it.\n#[cfg(test)]\npub const TOKENS_CSS: &str = {css:?};").unwrap();

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("tokens.rs");
    std::fs::write(out, rs).unwrap();
}
